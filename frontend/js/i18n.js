let current = 'en';

export function getLang() {
  return LANGS.find((l) => l.code === current);
}

export function setLang(code) {
  current = STRINGS[code] ? code : 'en';
  const lang = getLang();
  document.documentElement.lang = lang.code;
  document.documentElement.dir = lang.dir;
  try { localStorage.setItem('open-letter-lang', current); } catch { /* private mode */ }
  applyStatic();
}

export function detectLang() {
  try {
    const saved = localStorage.getItem('open-letter-lang');
    if (saved && STRINGS[saved]) return saved;
  } catch { /* private mode */ }
  for (const tag of navigator.languages || [navigator.language || 'en']) {
    const code = tag.toLowerCase().split('-')[0];
    if (STRINGS[code]) return code;
  }
  return 'en';
}

// t('days_left', { n: 3 }) -> "3 days left". Uses the `_one` form for 1 when a language has one.
export function t(key, vars = {}) {
  const table = STRINGS[current];
  const pluralKey = vars.n === 1 && table[`${key}_one`] ? `${key}_one` : key;
  const text = table[pluralKey] ?? STRINGS.en[pluralKey] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
}

export function formatDate(date) {
  return new Intl.DateTimeFormat(getLang().locale, { dateStyle: 'long', timeZone: 'UTC' }).format(date);
}

// Fill in every element marked with data-i18n (text) or data-i18n-attr ("placeholder:key; aria-label:key").
function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  });
}
